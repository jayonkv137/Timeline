#!/usr/bin/env python3
"""scripts/evidence_audit.py — Can every engine action quote be anchored to an exact place in its message?

Uses engine/evidence.py (the same anchoring the workspace projection uses), zero LLM calls.
Writes docs/plans/reports/SE_evidence_audit.md (EVIDENCE_SPEC §4, step SE.2).

Usage: python3 scripts/evidence_audit.py [--chats data/chats] [--out docs/plans/reports/SE_evidence_audit.md]
"""
from __future__ import annotations

import argparse
import collections
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from engine.evidence import EvidenceIndex, audit  # noqa: E402

ORDER = ["exact", "exact (repeated phrase)", "normalized", "normalized (repeated phrase)", "multipart", "message", "missing"]
LABEL = {
    "exact": "Exact, unique",
    "exact (repeated phrase)": "Exact, phrase repeats (placed by reading order)",
    "normalized": "Exact after formatting normalisation",
    "normalized (repeated phrase)": "Normalised, phrase repeats",
    "multipart": "Verbatim passages joined with “…” by the model",
    "message": "Not in its message → open the message, honest state",
    "missing": "No source action",
}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--chats", type=Path, default=REPO / "data" / "chats")
    ap.add_argument("--out", type=Path, default=REPO / "docs" / "plans" / "reports" / "SE_evidence_audit.md")
    a = ap.parse_args()
    total: collections.Counter = collections.Counter()
    rows, misses = [], []
    for d in sorted(a.chats.glob("c*")):
        if not (d / "state.json").exists() or not (d / "dialogue.json").exists():
            continue
        state = json.loads((d / "state.json").read_text(encoding="utf-8"))
        dialogue = json.loads((d / "dialogue.json").read_text(encoding="utf-8"))
        ev = EvidenceIndex(d.name, dialogue, state.get("actions", []))
        c = audit(ev)
        total.update(c)
        rows.append((d.name, sum(c.values()), c))
        for aid, res in sorted(ev.anchors.items()):
            if res["match"] in ("message", "missing"):
                q = (ev.actions.get(aid, {}).get("evidence_quote") or "").replace("\n", " ")
                misses.append((d.name, aid, res.get("note") or "", q[:90]))
    n = sum(total.values())
    anchored = n - total["message"] - total["missing"]
    lines = [
        "# SE evidence audit: can every engine quote be anchored to exact words?",
        "",
        f"Generated by `scripts/evidence_audit.py` (engine/evidence.py, zero LLM calls) on {len(rows)} chats, {n} actions.",
        "",
        f"**{anchored} of {n} ({100 * anchored / max(1, n):.1f}%) anchor on exact words; {n - anchored} open their message with an honest state.**",
        "",
        "| Result | Actions | Share |",
        "|---|---:|---:|",
    ]
    for k in ORDER:
        if total[k]:
            lines.append(f"| {LABEL[k]} | {total[k]} | {100 * total[k] / n:.1f}% |")
    lines += ["", "## Per chat", "", "| Chat | Actions | Anchored | Not in message |", "|---|---:|---:|---:|"]
    for name, cnt, c in rows:
        lines.append(f"| {name} | {cnt} | {cnt - c.get('message', 0) - c.get('missing', 0)} | {c.get('message', 0)} |")
    lines += ["", "## Not anchored (shown to the user as “Exact passage unavailable”)", "", "| Chat | Action | Note | Engine quote |", "|---|---|---|---|"]
    for name, aid, note, q in misses:
        lines.append(f"| {name} | `{aid}` | {note} | {q.replace('|', '/')} |")
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{anchored}/{n} anchored ({100 * anchored / max(1, n):.1f}%) → {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
